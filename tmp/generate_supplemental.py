def extract_words(text):
    """Extract all unique lowercase words from text."""
    words = re.findall(r'[A-Za-z\u00C0-\u00FF\u00e4\u00f6\u00fc\u00c4\u00d6\u00dc\u00df]+(?:-[A-Za-z\u00C0-\u00FF\u00e4\u00f6\u00fc\u00c4\u00d6\u00dc\u00df]+)*', text)
    return set(w.lower() for w in words)


def is_covered(word, existing_keys):
    """Check if a word is already covered by existing annotations (with fuzzy matching)."""
    if word in existing_keys:
        return True

    # Check if word appears in a multi-word key
    for k in existing_keys:
        if ' ' in k and word in k.split():
            return True

    # Check suffix stripping: try removing common German suffixes
    suffixes = ['s', 'es', 'en', 'n', 'er', 'em', 'e', 'ern', 'ens']
    for suffix in suffixes:
        if word.endswith(suffix) and len(word) > len(suffix) + 2:
            stem = word[:-len(suffix)]
            if stem in existing_keys:
                return True

    # For hyphenated words, check the last part
    if '-' in word:
        parts = word.split('-')
        last_part = parts[-1]
        if last_part in existing_keys:
            return True

    return False


def get_annotation(word):
    """Get annotation from master dict."""
    if word in MASTER_DICT:
        return MASTER_DICT[word]
    return None


def process_all():
    """Process all texts and generate supplemental annotations."""
    with open('/Users/ioana/c1-german-prep/tmp/batch1-texts-and-annotations.json') as f:
        b1 = json.load(f)
    with open('/Users/ioana/c1-german-prep/tmp/batch2-texts-and-annotations.json') as f:
        b2 = json.load(f)

    result = {}
    stats = {"total_added": 0, "total_missing": 0, "missing_words": set()}

    for batch in [b1, b2]:
        for prompt, examples in batch.items():
            result[prompt] = []

            for i, ex in enumerate(examples):
                text = ex['text']
                existing_keys = set(ex['word_annotations'].keys())

                # Extract all words
                all_words = extract_words(text)
                content_words = all_words - FUNCTION_WORDS

                # Find uncovered words
                supplemental = {}
                for word in sorted(content_words):
                    if not is_covered(word, existing_keys):
                        ann = get_annotation(word)
                        if ann:
                            supplemental[word] = ann
                            stats["total_added"] += 1
                        else:
                            stats["total_missing"] += 1
                            stats["missing_words"].add(word)

                result[prompt].append(supplemental)

    # Write output
    with open('/Users/ioana/c1-german-prep/tmp/supplemental-annotations.json', 'w', encoding='utf-8') as f:
        json.dump(result, f, ensure_ascii=False, indent=2)

    print(f"Total annotations added: {stats['total_added']}")
    print(f"Total words still missing: {stats['total_missing']}")
    if stats['missing_words']:
        missing_sorted = sorted(stats['missing_words'])
        print(f"\nMissing words ({len(missing_sorted)}):")
        for w in missing_sorted:
            print(f"  {w}")


if __name__ == '__main__':
    process_all()
